// MARK: - 配置（KISS：常量化，不散落魔法值）

enum Config {
    static let pollInterval: TimeInterval = 0.25    // 剪贴板轮询间隔（秒）
    static let displayDuration: TimeInterval = 1.4  // 提示停留时长（秒）
    static let pillHeight: CGFloat = 34             // 提示胶囊高度
    static let pillPadding: CGFloat = 14            // 胶囊水平内边距
    static let debug = CommandLine.arguments.contains("--debug")
}

func dlog(_ message: String) {
    if Config.debug { print("[CopyToast] \(message)") }
}

// MARK: - 复制内容分类

struct ToastInfo {
    let symbol: String
    let tint: NSColor
    let detail: String
}

/// 仅依据剪贴板「类型元数据」分类，绝不读取内容本身。
/// macOS 14 隐私机制：读取类型元数据不弹窗，读取实际数据才弹
/// “想要从其他 App 粘贴”提示 —— 本设计因此完全无打扰。
func classify(_ raw: Set<String>) -> ToastInfo? {
    // 密码管理器等保密内容：提示成功，但不读内容
    let concealed = raw.contains("org.nspasteboard.ConcealedType")
        || raw.contains("com.agilebits.onepassword")
    if concealed { return ToastInfo(symbol: "lock.fill", tint: .systemOrange, detail: "敏感内容") }

    // 拖拽会话等临时内容：不提示
    if raw.contains("org.nspasteboard.TransientType")
        || raw.contains("org.nspasteboard.AutoGeneratedType") { return nil }

    if raw.contains("public.file-url") || raw.contains("NSFilenamesPboardType") {
        return ToastInfo(symbol: "doc.fill", tint: .systemBlue, detail: "文件")
    }
    let types = raw.compactMap { UTType($0) }
    if types.contains(where: { $0.conforms(to: .image) }) {
        return ToastInfo(symbol: "photo.fill", tint: .systemPurple, detail: "图片")
    }
    if raw.contains("public.url") {
        return ToastInfo(symbol: "link", tint: .systemTeal, detail: "链接")
    }
    if raw.contains("NSStringPboardType") || types.contains(where: { $0.conforms(to: .text) }) {
        return ToastInfo(symbol: "checkmark.circle.fill", tint: .systemGreen, detail: "文本")
    }
    return ToastInfo(symbol: "doc.on.clipboard", tint: .secondaryLabelColor, detail: "内容")
}

// MARK: - 悬浮提示窗（不抢焦点、不可点击、鼠标附近弹出、自动消失）

final class ToastPresenter {
    private let panel: NSPanel
    private var showGeneration = 0
    private var dismissItem: DispatchWorkItem?

    init() {
        panel = NSPanel(contentRect: .zero,
                        styleMask: [.borderless, .nonactivatingPanel],
                        backing: .buffered, defer: false)
        panel.isFloatingPanel = true
        panel.level = .statusBar                       // 浮于普通窗口之上
        panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .ignoresCycle]
        panel.isOpaque = false
        panel.backgroundColor = .clear
        panel.hasShadow = true
        panel.ignoresMouseEvents = true                // 纯展示，不拦截任何点击
    }

    func show(_ info: ToastInfo) {
        showGeneration += 1
        let generation = showGeneration
        dismissItem?.cancel()

        let wasVisible = panel.isVisible && panel.alphaValue > 0.9

        let (view, size) = buildContent(info)
        panel.contentView = view
        panel.setContentSize(size)
        panel.setFrameOrigin(originFor(size: size))
        panel.orderFrontRegardless()

        if wasVisible {
            // 连续复制：原地更新内容并重新计时，不做闪现动画
            panel.alphaValue = 1
        } else {
            panel.alphaValue = 0
            NSAnimationContext.runAnimationGroup { ctx in
                ctx.duration = 0.16
                ctx.timingFunction = CAMediaTimingFunction(name: .easeOut)
                self.panel.animator().alphaValue = 1
            }
        }

        let item = DispatchWorkItem { [weak self] in self?.dismiss(generation: generation) }
        dismissItem = item
        DispatchQueue.main.asyncAfter(deadline: .now() + Config.displayDuration, execute: item)
    }

    private func dismiss(generation: Int) {
        guard generation == showGeneration else { return }
        let up = NSPoint(x: panel.frame.origin.x, y: panel.frame.origin.y + 10)
        NSAnimationContext.runAnimationGroup({ ctx in
            ctx.duration = 0.22
            ctx.timingFunction = CAMediaTimingFunction(name: .easeIn)
            self.panel.animator().alphaValue = 0
            self.panel.animator().setFrameOrigin(up)
        }, completionHandler: { [weak self] in
            // 期间若有新的复制（generation 已变化），不关闭窗口
            if self?.showGeneration == generation { self?.panel.orderOut(nil) }
        })
    }

    /// 优先出现在鼠标上方；多屏下约束在鼠标所在屏幕的安全区内
    private func originFor(size: NSSize) -> NSPoint {
        let mouse = NSEvent.mouseLocation
        let screen = NSScreen.screens.first(where: { NSPointInRect(mouse, $0.frame) })
            ?? NSScreen.main ?? NSScreen.screens[0]
        let vf = screen.visibleFrame
        let x = min(max(mouse.x - size.width / 2, vf.minX + 8), vf.maxX - size.width - 8)
        let y = min(max(mouse.y + 18, vf.minY + 8), vf.maxY - size.height - 8)
        return NSPoint(x: x, y: y)
    }

    /// 手工布局：确定性尺寸，避免 Auto Layout 在无父窗口场景下的歧义
    private func buildContent(_ info: ToastInfo) -> (NSView, NSSize) {
        let H = Config.pillHeight

        let icon = NSImageView(frame: NSRect(x: 0, y: (H - 18) / 2, width: 18, height: 18))
        let symbolConfig = NSImage.SymbolConfiguration(pointSize: 14, weight: .medium)
        icon.image = NSImage(systemSymbolName: info.symbol, accessibilityDescription: nil)?
            .withSymbolConfiguration(symbolConfig)
        icon.contentTintColor = info.tint

        let title = NSTextField(labelWithString: "已复制")
        title.font = .systemFont(ofSize: 13.5, weight: .semibold)
        let ts = title.intrinsicContentSize
        title.frame = NSRect(x: 0, y: (H - ts.height) / 2 - 1, width: ts.width, height: ts.height)

        var views: [(NSView, CGFloat)] = [(icon, 6), (title, 4)]   // (视图, 其后间距)
        var contentWidth: CGFloat = 18 + 6 + ts.width
        if !info.detail.isEmpty {
            let detail = NSTextField(labelWithString: "· \(info.detail)")
            detail.font = .systemFont(ofSize: 12.5, weight: .regular)
            detail.textColor = .secondaryLabelColor
            let ds = detail.intrinsicContentSize
            detail.frame = NSRect(x: 0, y: (H - ds.height) / 2 - 0.5, width: ds.width, height: ds.height)
            views.append((detail, 0))
            contentWidth += 4 + ds.width
        }
        let W = contentWidth + Config.pillPadding * 2

        let bg = NSVisualEffectView(frame: NSRect(x: 0, y: 0, width: W, height: H))
        bg.material = .popover
        bg.blendingMode = .behindWindow
        bg.state = .active
        bg.wantsLayer = true
        bg.layer?.cornerRadius = H / 2
        bg.layer?.masksToBounds = true

        var x = Config.pillPadding
        for (v, spacing) in views {
            var f = v.frame
            f.origin.x = x
            v.frame = f
            bg.addSubview(v)
            x += f.width + spacing
        }
        return (bg, NSSize(width: W, height: H))
    }
}

// MARK: - 应用主体

func updateLoginItem(_ item: NSMenuItem, for status: SMAppService.Status) {
    item.title = "登录时启动"
    item.state = .off
    switch status {
    case .notRegistered: break
    case .enabled: item.state = .on
    case .requiresApproval:
        item.title = "登录时启动（等待系统批准…）"
        item.state = .mixed
    case .notFound: item.title = "登录项不可用，查看系统设置…"
    @unknown default: item.title = "查看系统登录项设置…"
    }
}

final class AppDelegate: NSObject, NSApplicationDelegate, NSMenuDelegate {
    private let loginItem = NSMenuItem()
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount = 0
    private let toast = ToastPresenter()
    private var statusItem: NSStatusItem!

    func applicationDidFinishLaunching(_ notification: Notification) {
        NSApp.setActivationPolicy(.accessory)   // 无 Dock 图标，纯后台
        lastChangeCount = pasteboard.changeCount
        setupStatusItem()
        Timer.scheduledTimer(withTimeInterval: Config.pollInterval, repeats: true) { [weak self] _ in
            self?.poll()
        }
        dlog("启动完成，初始 changeCount=\(lastChangeCount)")
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        guard let rawTypes = pasteboard.types, !rawTypes.isEmpty else {
            dlog("剪贴板已清空，忽略")
            return
        }
        let raw = Set(rawTypes.map { $0.rawValue })
        dlog("剪贴板变化：\(raw.sorted())")

        guard let info = classify(raw) else {
            dlog("临时内容，跳过提示")
            return
        }
        dlog("展示提示：\(info.detail)")
        toast.show(info)
    }

    // MARK: 菜单栏图标（唯一的可见入口：查看状态 / 开机自启 / 退出）

    private func setupStatusItem() {
        statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.variableLength)
        statusItem.button?.image = NSImage(systemSymbolName: "doc.on.clipboard.fill",
                                           accessibilityDescription: "复制提示")

        let menu = NSMenu()
        let running = NSMenuItem(title: "复制提示 · 正在运行", action: nil, keyEquivalent: "")
        running.isEnabled = false
        menu.addItem(running)
        menu.addItem(.separator())

        menu.delegate = self
        loginItem.target = self
        loginItem.action = #selector(toggleLaunchAtLogin(_:))
        updateLoginItem(loginItem, for: SMAppService.mainApp.status)
        menu.addItem(loginItem)
        menu.addItem(.separator())

        let quit = NSMenuItem(title: "退出", action: #selector(quit), keyEquivalent: "q")
        quit.target = self
        menu.addItem(quit)

        statusItem.menu = menu
    }

    func menuNeedsUpdate(_ menu: NSMenu) {
        updateLoginItem(loginItem, for: SMAppService.mainApp.status)
    }

    @objc private func toggleLaunchAtLogin(_ sender: NSMenuItem) {
        let service = SMAppService.mainApp
        do {
            switch service.status {
            case .enabled: try service.unregister()
            case .notRegistered: try service.register()
            case .requiresApproval, .notFound: SMAppService.openSystemSettingsLoginItems()
            @unknown default: SMAppService.openSystemSettingsLoginItems()
            }
        } catch {
            dlog("登录项设置失败：\(error.localizedDescription)")
            SMAppService.openSystemSettingsLoginItems()
        }
        updateLoginItem(sender, for: service.status)
    }

    @objc private func quit() {
        NSApp.terminate(nil)
    }
}


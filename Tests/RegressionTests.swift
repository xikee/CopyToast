import AppKit
import ServiceManagement

func runRegressionTests() {
    let samples: [(Set<String>, String?)] = [
        (["public.heic"], "图片"),
        (["org.webmproject.webp"], "图片"),
        (["public.png", "public.utf8-plain-text"], "图片"),
        (["public.rtf"], "文本"),
        (["public.utf8-plain-text"], "文本"),
        (["NSStringPboardType"], "文本"),
        (["public.file-url", "public.url", "public.png"], "文件"),
        (["NSFilenamesPboardType"], "文件"),
        (["public.url", "public.utf8-plain-text"], "链接"),
        (["org.nspasteboard.ConcealedType", "public.rtf"], "敏感内容"),
        (["com.agilebits.onepassword", "org.nspasteboard.TransientType"], "敏感内容"),
        (["org.nspasteboard.AutoGeneratedType", "public.heic"], nil),
        (["org.nspasteboard.TransientType", "public.png"], nil),
        (["com.example.copytoast-unknown"], "内容")
    ]
    for (types, expected) in samples {
        let actual = classify(types)?.detail
        precondition(actual == expected, "分类错误：\(types) → \(String(describing: actual))")
    }

    // 复用同一个菜单项，覆盖用户在系统设置里更改状态后再次打开菜单的情况。
    let item = NSMenuItem()
    let states: [(SMAppService.Status, String, NSControl.StateValue)] = [
        (.requiresApproval, "登录时启动（等待系统批准…）", .mixed),
        (.enabled, "登录时启动", .on),
        (.notRegistered, "登录时启动", .off),
        (.notFound, "登录项不可用，查看系统设置…", .off)
    ]
    for (status, title, state) in states {
        updateLoginItem(item, for: status)
        precondition(item.title == title && item.state == state, "登录项状态错误：\(status.rawValue)")
    }
    print("通过 \(samples.count) 组剪贴板分类和 \(states.count) 组登录项菜单状态测试")
}
